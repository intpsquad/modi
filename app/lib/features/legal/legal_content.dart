/// 약관/정책 문서 구분.
enum LegalDoc {
  terms('이용약관'),
  privacy('개인정보 처리방침');

  const LegalDoc(this.label);

  /// 세그먼트/타이틀에 쓰는 짧은 이름.
  final String label;
}

/// 문서 한 절(제목 + 본문).
class LegalSection {
  const LegalSection(this.heading, this.body);

  final String heading;
  final String body;
}

/// 제목·시행일·본문 절 묶음.
class LegalDocument {
  const LegalDocument({
    required this.doc,
    required this.title,
    required this.sections,
  });

  final LegalDoc doc;
  final String title;
  final List<LegalSection> sections;
}

/// 문서 구분으로 본문을 찾는다.
LegalDocument legalDocumentFor(LegalDoc doc) =>
    doc == LegalDoc.privacy ? kPrivacyPolicy : kTermsOfService;

