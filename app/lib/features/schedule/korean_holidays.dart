///
/// **왜 계산이 아니라 표인가**: 설날·추석·부처님오신날은 음력이고 대체공휴일은 요일에 따라 붙어,
/// 규칙만으로는 날짜를 유도할 수 없다. 그래서 연도별로 확정 날짜를 박아 둔다(2026-08-07 사용자 확정 —
