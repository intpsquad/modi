///
/// **표에 없는 연도는 공휴일을 칠하지 않는다**(일요일 빨간색은 표와 무관하게 계속 동작한다).
/// 매년 관보에 다음 해 월력요항이 실리면 그때 연도를 추가한다 — `specs/OPEN.md`에 후속으로 기록돼 있다.
///
/// **주의**: 2026년에 「공휴일에 관한 법률」이 두 차례(2026-02-10, 2026-04-09) 개정돼
/// **제헌절이 18년 만에 부활하고 노동절이 관공서 공휴일로 추가**됐다. 기억이나 옛 표를 베끼지 말고
