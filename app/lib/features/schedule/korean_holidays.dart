/// 표에 담긴 날짜의 단일 진실. 키는 `'MM-DD'`, 값은 사람이 읽는 공휴일 이름이다.
/// 이름은 색 판정(`isHoliday`)뿐 아니라 2026-08-08부터 UI에도 쓰인다 —
/// 일정 탭 목록 상단·홈 주간 미리보기에 `HolidayCard`로 이름을 일정처럼 보여준다(`nameOf`).
class KoreanHolidays {
  KoreanHolidays._();

  /// 이 표가 커버하는 연도. 여기 없는 해는 [isHoliday]가 항상 false다.
  static Set<int> get supportedYears => _byYear.keys.toSet();

  /// [year]에 등록된 공휴일 전체를 `'MM-DD'`로 돌려준다(없는 해는 빈 집합).
  /// 테스트가 표 전체를 스냅샷으로 붙잡아 두는 데 쓴다 — 날짜가 빠지든 엉뚱한 날이
  /// 끼어들든 한쪽만 세는 개수 비교와 달리 둘 다 걸린다.
  static Set<String> datesIn(int year) => _byYear[year]?.keys.toSet() ?? {};

  /// [date]가 관공서 공휴일이면 true. 시·분이 붙어 있어도 날짜만 본다.
  static bool isHoliday(DateTime date) => nameOf(date) != null;

  /// 공휴일이면 이름, 아니면 null.
  static String? nameOf(DateTime date) {
    final table = _byYear[date.year];
    if (table == null) return null;
    return table[_key(date)];
  }

  static String _key(DateTime date) =>
      '${date.month.toString().padLeft(2, '0')}-'
      '${date.day.toString().padLeft(2, '0')}';

