-- 자료 임베딩. 추천 자료 선별(RAG 2단계)의 전제다 — 방 목표와 관련 있는 자료 K개만
-- 프롬프트에 넣으려면 자료마다 벡터가 있어야 하는데, 추천을 누를 때마다 아카이브 전체를 다시
-- 임베딩할 수는 없다(자료 20건 × 약 1.4초). 그래서 등록 시점에 한 번 만들어 여기에 둔다.
--
-- ⚠️ 이 티켓 범위에서는 아무도 이 컬럼을 읽지 않는다. 읽는 쪽(유사도 계산·선별)은 다음 티켓이다.
--
-- 타입이 pgvector 의 vector 가 아니라 real[] 인 이유 (2026-08-01 확정, ai/docs/DECISIONS.md):
--   확정된 설계가 "FastAPI 가 메모리에서 선별"이라 Postgres 는 벡터로 검색하지 않는다. pgvector 가
--   주는 것(전용 타입·거리 연산자 <=> · HNSW 인덱스) 중 실제로 쓰는 것은 저장뿐인데, 그 대가로
--   운영·로컬 이미지를 pgvector 빌드로 바꾸고 Testcontainers 테스트를 전부 손봐야 한다.
--   Postgres 에서 top-K 를 돌릴 근거가 생기면 그때 옮긴다 — real[] → vector 는 컬럼 하나짜리 작업이다.
--   real(4바이트)로 충분하다: 코사인 유사도 판정에 float8 정밀도가 필요하지 않고, 1536차원 × 8바이트면
--   행당 12KB 가 된다.
--
-- 차원을 제약으로 걸지 않는다. real[] 는 길이를 강제할 수 없고(Postgres 배열의 선언 길이는 문서일 뿐
-- 검사되지 않는다), 임베딩 모델을 바꾸면 차원이 달라진다 — 섞인 차원은 읽는 쪽에서 걸러야 한다.
-- 현재 모델 text-embedding-3-small = 1536차원.
--
-- nullable 이다. NULL 이 정상인 경우가 넷 있다:
--   ① 이 마이그레이션 이전에 등록된 자료 — 기본은 백필하지 않는다(크레딧을 쓴다).
--      필요하면 modi.archive.backfill-embeddings=true 로 기동해 채운다.
--   ② crawl_status = 'PENDING' — 임베딩할 본문·요약이 아직 없다.
--   ③ 임베딩 LLM 호출 실패 — 태깅·요약과 같은 폴백으로 등록 자체는 막지 않는다.
--   ④ 본문도 요약도 없는 자료.
-- NULL 인 자료는 나중에 유사도 축에서만 빠지고 최근성·핀/좋아요 축으로 후보에 남는다
-- (하이브리드 선별을 고른 덕에 생긴 부수 효과, ai/docs/DECISIONS.md).
--
-- 인덱스를 만들지 않는다. real[] 에 걸 수 있는 인덱스는 이 용도에 쓸모가 없고(거리 연산자가 없다),
-- 읽기 패턴은 "방 하나의 자료를 전부 가져와 메모리에서 비교"라 room_id 인덱스로 충분하다.
ALTER TABLE archive_items ADD COLUMN embedding real[];
