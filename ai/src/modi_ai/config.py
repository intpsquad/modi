"""환경 설정. 값은 ai/.env 에서 읽고, 없으면 아래 기본값을 쓴다.

키(OPENAI_API_KEY·INTERNAL_API_KEY·LANGSMITH_API_KEY)는 기본값을 빈 문자열로 둔다 —
없는 상태로도 서버가 뜨고 헬스체크가 동작해야 하기 때문이다. 실제로 키가 필요한
엔드포인트를 만들 때 그 시점에 검증한다.
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # OpenAI (직접 호출)
    # 🔴 2026-08-13: 게이트웨이 경유 → OpenAI 직접 호출로 바꿨고, 회수된 게이트웨이의 이름을
    # 딴 필드명도 이 이름으로 개명했다. 값은 OpenAI 플랫폼 키(sk-...)다.
    # ⚠️ 이 이름을 또 바꿀 때는 운영 .env 를 **같은 배포에서** 함께 바꿔야 한다 — 어긋나면
    # 서버는 정상 부팅하고 AI 기능만 조용히 꺼진다(아래 키가 빈 문자열이어도 뜨기 때문이다).
    openai_api_key: str = ""
    openai_base_url: str = "https://api.openai.com/v1/"
    # 투두 추천 생성 모델. 2026-07-30 사용자 지시로 gpt-4.1-mini 에서 교체.
    # 2026-08-13: 태깅·요약도 이 값으로 통일됐다(EXPERIMENTS #34) — 세 기능이 한 모델을 쓴다.
    # ⚠️ **추천 워크로드로 재본 실측이 아직 없다** — 사용자가 "이 모델로 가고 근거는 결과를 내며
    # 찾는다"로 확정했다. 없는 근거를 있는 것처럼 적지 않기 위해 그대로 남긴다(docs/DECISIONS.md).
    # 참고로 가진 인접 실측은 요약 워크로드뿐이다(EXPERIMENTS #14: 1.3~2.8초 · 추론 토큰 0).
    openai_model: str = "gpt-5.4-nano"
    openai_embedding_model: str = "text-embedding-3-small"

    # 프롬프트의 "아카이브 자료" 절에 넣을 수 있는 최대 글자 수. 넘으면 뒤쪽 자료부터
    # 버린다(`ranking.select_archive`).
    #
    # ⚠️ **2026-08-09: 성격이 바뀌었다 — 안전밸브가 아니라 상시 발동하는 선별기다.**
    # 원래 값 12,000 은 "발동하지 않는 크기"를 노린 것이었는데(자료 약 58건분), 시연 응답시간
    # 목표(5초) 때문에 **입력을 고정 상한으로 묶기로 했다**(사용자 확정). 3,000 자는 206자/건
    # 실측 기준 **약 14~15건**이다.
    #
    # 근거가 된 실측:
    #   · 2026-08-02 방 "회화 스터디" 자료 18건 = 렌더 합계 3,709자(206자/건, input 2,982 tok)
    #   · 2026-08-09 운영 방 "춘천여행" 자료 35건 = 앱 실측 응답 25.9 / 28.5 / 30.1초
    #
    # ⚠️ **품질은 재지 않았다.** "자료가 몇 건일 때 추천 품질이 나빠지는가"는 여전히 모른다 —
    # 이 값은 품질이 아니라 지연을 근거로 정했다. 자료가 15건 넘는 방은 오래된 자료가 추천
    # 근거에서 빠진다는 뜻이고, 그 대가를 알고 받았다.
    archive_prompt_budget_chars: int = 3_000

    # 예산 안에 넣을 자료를 **최신순**으로 고를지, 기존 4축 가중 순위(좋아요·핀·목표유사도·
    # 최근성)로 고를지.
    #
    # **True 로 확정했다**(2026-08-09 사용자 확정). 예산이 상시 발동하게 되면서 "무엇이 잘리는가"가
    # 처음으로 중요해졌고, 시연에서는 **직전에 추가한 자료가 반드시 들어가는 것**이 요구사항이다.
    # 순위로 고르면 방금 넣은 자료가 좋아요 0·핀 없음이라 밀려날 수 있다.
    #
    # 곁딸린 이득 하나: 최신순에는 목표 벡터가 필요 없어 `suggest._select_archive` 의 **임베딩
    # 왕복 1회가 LLM 앞에서 통째로 빠진다**.
    #
    # ⚠️ **대가 — 핀·좋아요·목표 유사도가 선별에서 빠진다.** 방 목표와 무관한 최신 자료가
    # 프롬프트를 채울 수 있고, 그 영향은 재지 않았다. False 로 두면 이전 동작으로 정확히
    # 돌아간다 — `critique_max_attempts` 와 같은 이유로 순위 코드를 지우지 않고 남긴다.
    archive_select_by_recency: bool = True

    # 후보 생성을 최대 몇 번까지 하는가. `0` 이면 검수 노드를 아예 안 탄다
    # (전환 전과 완전히 같은 동작), `1` 이면 검수만, `2` 이상이면 전부 반려됐을 때 재생성한다.
    #
    # **1 로 확정했다** — 0/1/2 를 나란히 재고 정했다(`docs/EXPERIMENTS.md` #28).
    # 착수 시점의 계획은 2(재생성 1회)였는데 **실측이 뒤집었다**: 재생성이 오히려 나쁘다.
    # 각 조건을 두 번씩 돌렸고, 세는 것은 **사용자가 지목한 나쁜 모양**의 비율이다
    # (`짜기`·`묶기`·`넣기`·`고르기` … — 좋은 동사를 열거하는 지표는 무너졌다, #28 ①③).
    #
    #                  부산 메타 행위   라운드 평균   7초 이상
    #   0 (검수 없음)      40%           3.6~3.9초    0/30
    #   1 (검수만)         0% · 5.9%     5.3~6.8초    8/60  ← 채택
    #   2 (재생성 1회)     22% · 3.0%    5.4~6.2초    3/60
    #
    # **1 을 고른 이유는 "2 가 나빠서"가 아니라 "구분이 안 돼서"다** — 3개 축에서 2 가 같거나
    # 낫고(지연 포함), 1 vs 2 는 #28 이 세운 기준을 통과하지 못한다. 싼 쪽을 골랐다
    # (라운드당 LLM 2회 · 2 는 최악 4회).
    #
    # 대가 둘을 사용자가 알고 받았다(2026-08-03): 후보가 절반 이하(88 → 41개, 3회차 최소 0),
    # 그리고 **13%의 라운드가 7초 상한을 넘는다**(최악 10.88초).
    #
    # ⚠️ **그래서 `critique → generate` 되돌아가는 엣지는 운영에서 안 탄다.** 코드는 남긴다 —
    # 조건 하나로 다시 재볼 수 있어야 하기 때문이다. **그래프 덕분에 좋아진 것이 아니다** —
    # 검수라는 아이디어가 올린 것이고, 그 판단은 `docs/EXPERIMENTS.md` #28 ④-1 에 적혀 있다.
    critique_max_attempts: int = 1

    # 검수가 후보를 **일부만** 반려했을 때도 되돌아가 다시 생성하는가.
    #
    # `critique_max_attempts` 와 **일부러 분리했다.** 그 값에 이 트리거를 얹으면 #28 이 얼려둔
    # 조건 2 스냅샷이 같은 `2` 인데 다른 동작을 가리키게 된다 — A/B 의 의미가 조용히 무너진다.
    #
    # ⚠️ **끄면(False) 모든 경로가 와 완전히 같다.** 그 동일성이 #28 기준선을
    # 재사용할 수 있는 근거이고, `tests/test_partial_retry.py` 가 지킨다.
    #
    # **False 로 확정했다 — 재보고 기각했다**(`docs/EXPERIMENTS.md` #29). 목적이던 후보 회복은
    # 실제로 됐는데(부산 41 → 109·88개, 오픽 55 → 93·103개) 두 가지가 막았다.
    #
    #                    10초 이상        부산 메타      오픽 메타
    #   끔 (채택)        0/30 · 1/30      0.0% · 5.9%   7.7% · 6.6%
    #   켬               11/30 · 12/30    7.6% · 12.7%  4.3% · 3.0%
    #
    # ① **지연.** 라운드당 LLM 이 2회 → 4회가 된다. 사용자가 이 티켓 때문에 7초에서 10초로
    #    올려준 상한마저 **37%·40%** 가 넘고 최악이 15.46초다. 두 실행이 3%p 차라 변동이 아니다.
    # ② **방마다 방향이 반대다.** 회화 스터디는 좋아졌는데(메타 ↓) 부산은 나빠졌다 —
    #    **하필 사용자가 불만을 제기한 방이다.** 왜 그런지는 모른다(#29 ②).
    #
    # 코드는 남긴다 — 조건 하나로 다시 잴 수 있어야 하기 때문이다. 다시 재기 전에 **#29 ④의
    # 검수 fail-open 을 먼저 고쳐야 한다** — 부산 방 라운드가 그만큼 오염돼 있다.
    regenerate_on_partial_reject: bool = False

    # Spring 만 호출할 수 있게 하는 공유 시크릿
    internal_api_key: str = ""

    # LangSmith — 운영에서는 반드시 false.
    # 이 값들은 그냥 두면 SDK 에 닿지 않는다(SDK 는 os.environ 만 본다) — `tracing.py` 참고.
    langsmith_tracing: bool = False
    langsmith_api_key: str = ""
    langsmith_project: str = "modi-ai"


@lru_cache
def get_settings() -> Settings:
    return Settings()
